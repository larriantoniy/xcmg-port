import type { Product, ProductSpecification } from "@/types/product";

type SpecificationInput = [label: string, value: string, unit?: string];

function specifications(sourceId: string, rows: SpecificationInput[]): ProductSpecification[] {
  return rows.map(([label, value, unit]) => ({
    label,
    value,
    unit,
    verificationStatus: "verified",
    sourceIds: [sourceId],
  }));
}

interface ProductInput {
  model: string;
  slug: string;
  description: string;
  sourceId: string;
  specifications: SpecificationInput[];
}

function richstacker(input: ProductInput): Product {
  return {
    id: `xcmg-${input.slug}`,
    slug: input.slug,
    brand: "XCMG",
    model: input.model,
    category: "Ричстакеры",
    title: `Ричстакер XCMG ${input.model}`,
    description: input.description,
    applications: ["Перемещение и штабелирование гружёных контейнеров"],
    media: { hero: null, gallery: [] },
    specifications: specifications(input.sourceId, input.specifications),
    verificationStatus: "verified",
    sourceIds: [input.sourceId],
    seo: {
      title: `Ричстакер XCMG ${input.model} — характеристики`,
      description: `Технические характеристики ричстакера XCMG ${input.model}: грузоподъёмность, высота подъёма, габариты и другие подтверждённые параметры.`,
    },
  };
}

