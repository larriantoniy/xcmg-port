import type { Product, ProductFeature, ProductSpecification } from "@/types/product";

type SpecificationInput = [group: ProductSpecification["group"], label: string, value: string, unit?: string];
type FeatureInput = [title: string, description: string];

interface ProductInput {
  model: string;
  slug: string;
  driveType: Product["driveType"];
  description: string;
  overview: string[];
  applications: string[];
  features: FeatureInput[];
  selectionReasons: string[];
  faq: Product["faq"];
  keySpecificationLabels: string[];
  sourceId: string;
  specifications: SpecificationInput[];
  seo: Product["seo"];
}

function specifications(sourceId: string, rows: SpecificationInput[]): ProductSpecification[] {
  return rows.map(([group, label, value, unit]) => ({
    group,
    label,
    value,
    unit,
    verificationStatus: "verified",
    sourceIds: [sourceId],
  }));
}

function features(sourceId: string, rows: FeatureInput[]): ProductFeature[] {
  return rows.map(([title, description]) => ({ title, description, verificationStatus: "verified", sourceIds: [sourceId] }));
}

function richstacker(input: ProductInput): Product {
  return {
    id: `xcmg-${input.slug}`,
    slug: input.slug,
    brand: "XCMG",
    model: input.model,
    category: "Ричстакеры",
    title: `Ричстакер XCMG ${input.model}`,
    driveType: input.driveType,
    description: input.description,
    overview: input.overview,
    applications: input.applications,
    features: features(input.sourceId, input.features),
    selectionReasons: input.selectionReasons,
    faq: input.faq,
    keySpecificationLabels: input.keySpecificationLabels,
    specifications: specifications(input.sourceId, input.specifications),
    verificationStatus: "verified",
    sourceIds: [input.sourceId],
    seo: input.seo,
  };
}

